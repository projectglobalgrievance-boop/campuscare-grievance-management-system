"""Train the complaint categorizer and write MODEL_REPORT.md.

Run:  python training/train.py
"""
from __future__ import annotations

import csv
from datetime import datetime, timezone
from pathlib import Path

import joblib
from sklearn.metrics import accuracy_score, classification_report, f1_score
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.svm import LinearSVC

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "complaints.csv"
MODEL_OUT = ROOT / "models" / "categorizer.joblib"
REPORT_OUT = ROOT / "MODEL_REPORT.md"


def main(csv_path: Path | None = None) -> None:
    with open(csv_path or DATA, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    texts = [r["description"] for r in rows]
    labels = [r["category"] for r in rows]

    x_train, x_test, y_train, y_test = train_test_split(
        texts, labels, test_size=0.2, random_state=42, stratify=labels)

    pipeline = Pipeline([
        ("tfidf", TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True,
                                  min_df=1, stop_words="english")),
        ("clf", LinearSVC(C=1.0, random_state=42)),
    ])
    pipeline.fit(x_train, y_train)

    preds = pipeline.predict(x_test)
    acc = accuracy_score(y_test, preds)
    macro_f1 = f1_score(y_test, preds, average="macro")
    report = classification_report(y_test, preds)

    MODEL_OUT.parent.mkdir(exist_ok=True)
    joblib.dump(pipeline, MODEL_OUT)

    REPORT_OUT.write_text(f"""# Model Report — Complaint Categorizer

- **Trained:** {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}
- **Algorithm:** TF-IDF (1–2 grams, sublinear TF, English stopwords) + LinearSVC (C=1.0)
- **Dataset:** {len(rows)} synthetic labeled campus complaints ({DATA.name}), 80/20 stratified split
- **Accuracy (test):** {acc:.3f}
- **Macro F1 (test):** {macro_f1:.3f}

## Per-class report

```
{report}
```

## Notes

- Dataset is synthetic (generated by `data/generate_dataset.py`, seed 42) —
  retrain with real complaints after launch for production-grade accuracy.
- Model file: `models/categorizer.joblib`, loaded lazily by `app/categorize.py`.
- If the model file is absent the service degrades to a keyword heuristic
  instead of failing.
""", encoding="utf-8")

    print(f"accuracy={acc:.3f} macro_f1={macro_f1:.3f}")
    print(f"model -> {MODEL_OUT}")
    print(f"report -> {REPORT_OUT}")


if __name__ == "__main__":
    main()
